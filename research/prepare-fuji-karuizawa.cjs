// Explicit selection from research; pending records are never imported automatically.
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const inventory=JSON.parse(fs.readFileSync(path.join(__dirname,'fuji-karuizawa-inventory.source.json'),'utf8'));
const audit=JSON.parse(fs.readFileSync(path.join(__dirname,'fuji-karuizawa-coordinate-audit.source.json'),'utf8'));
const selected=[
  ['fuji-kawaguchiko-momiji-corridor',null,'梨川沿岸的紅葉步道，與紅葉隧道是不同景點。'],
  ['fuji-kawaguchiko-momiji-tunnel',null,'道路沿線的紅葉觀賞區。地圖標記不是停車入口，請使用合法停車空間。'],
  ['fuji-asahigaoka','山梨県南都留郡山中湖村（旭日丘湖畔緑地公園・番地未確認）','湖畔步道可賞楓。整體紅葉約10月下旬至11月上旬，楓樹個別見頃待確認。'],
  ['fuji-murayama-sengen',null,'縣指定天然紀念物銀杏。地址為文化財所在地；開放與入口請依現場公告。'],
  ['fuji-niihashi-sengen',null,'境內有楓樹與銀杏，各自見頃待確認。社務所休息時仍可進入境內，請尊重參拜空間。'],
  ['karuizawa-usui-lookout',null,'位於長野與群馬縣界。整體紅葉約10月中旬至11月上旬，楓樹個別見頃待確認。'],
  ...['karuizawa-kumoba','fuji-museum-park','fuji-kitaguchi-sengen','fuji-tanuki-lake',
    'fuji-shiraito-falls','fuji-chichibunomiya','fuji-fujioka-ginkgo'].map(id=>[id,null,null])
];
assert.equal(new Set(selected.map(s=>s[0])).size,13);
const sources={};
const spots=selected.map(([id,address,note])=>{
  const s=inventory.spots.find(s=>s.id===id),review=audit.spots.find(s=>s.id===id);
  assert.ok(s&&review,id);
  assert.deepEqual(s.coordinates,review.acceptedResearchCoordinates,id);
  assert.ok(s.coordinates===null||(Number.isFinite(s.coordinates?.lat)&&Number.isFinite(s.coordinates?.lng)),id);
  assert.ok(s.maple.present===true||s.ginkgo.present===true,id);
  if(s.coordinates) assert.equal(s.coordinateEvidence.fieldVerified,false);
  for(const type of ['maple','ginkgo']){
    assert.ok([true,null].includes(s[type].present));
    if(s[type].peak){
      assert.equal(s[type].peak.scope,`${type}_specific`);
      assert.ok(s[type].peak.start&&s[type].peak.end);
    }
  }
  if(s.mixedAutumn?.present===true){
    const peak=s.mixedAutumn.peak;
    if(peak){
      assert.equal(peak.scope,'mixed_autumn_not_species_specific');
      assert.ok(peak.start&&peak.end&&inventory.sources[peak.source]);
      assert.deepEqual(peak,s.autumnReference);
    }
    for(const plant of s.mixedAutumn.plants||[]){
      assert.ok(plant.name&&plant.sourceIds.length);
      for(const key of plant.sourceIds)assert.ok(s.sourceIds.includes(key)&&inventory.sources[key]);
    }
  }
  for(const key of s.sourceIds){assert.ok(inventory.sources[key],key);sources[key]=inventory.sources[key];}
  return {id:s.id,ja:s.ja,zh:s.zh,area:s.proposedArea,prefecture:s.prefecture,municipality:s.municipality,
    address:address||s.address,addressPrecision:s.addressPrecision,coordinates:s.coordinates,
    xSearchName:s.xSearchName,aliases:s.aliases,sources:s.sourceIds,maple:s.maple,ginkgo:s.ginkgo,
    autumnReference:s.autumnReference,mixedAutumn:s.mixedAutumn||null,researchedAt:s.researchedAt,note:note||s.note||s.researchNotes,
    coordinateReview:s.coordinates?{reviewedAt:audit.checkedAt,kind:s.coordinateEvidence.kind,sourceUrl:inventory.sources[s.coordinateEvidence.sourceId].url,
      entranceVerified:false,viewingAreaConfirmed:false,displayDisclaimer:'景點區域示意，非已核實入口或單株位置'}:null,
    integration:{status:s.coordinates?'selected_for_app_area_marker':'selected_for_app_list_only',
      missingChecks:s.integration.selectedForLocalApp?s.integration.missingChecks:['verify_entrance_before_travel']}};
});
assert.equal(spots.filter(s=>s.coordinates).length,9);
assert.deepEqual(spots.filter(s=>!s.coordinates).map(s=>s.id),[
  'fuji-tanuki-lake','fuji-shiraito-falls','fuji-chichibunomiya','fuji-fujioka-ginkgo'
]);
assert.equal(spots.find(s=>s.id==='fuji-asahigaoka').ginkgo.present,null);
assert.ok(!JSON.stringify({sources,spots}).includes('AIza'));
const output='// Generated by research/prepare-fuji-karuizawa.cjs; selected records only.\nconst regionalFoliageResearch = '+JSON.stringify({researchDate:inventory.researchDate,sources,spots},null,2)+';\n';
const target=path.join(root,'dist/fuji-karuizawa-data.js');
if(process.argv.includes('--check'))assert.equal(fs.readFileSync(target,'utf8'),output,'Regenerate Fuji/Karuizawa data');
else fs.writeFileSync(target,output);
console.log('PASS: 13 explicitly selected destinations, 9 source representative points, 4 list-only, independent species/mixed dates and reproducible data.');
